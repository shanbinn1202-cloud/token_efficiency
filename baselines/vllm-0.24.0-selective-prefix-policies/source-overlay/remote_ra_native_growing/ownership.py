"""Real vLLM BlockPool reference ownership, outside its exact-prefix hash table.

This module operates on KVCacheBlock instances from the actual pool. Tests use
the exact pinned BlockPool methods extracted from source, not a simulated set
controller. No worker/kernel support is claimed by reference-count operations.

Stage B references (spec 3.7): S = session pin (``sessions[ns]`` complete
resident Pages and ``tails[ns]`` the live tail block), Q = request row
reference, F = phase-1 lease reference. Admission turns F into Q for the
adopted phase-1 blocks without a refcount change. One block per Page per
FullAttention group (w = 1): a Page maps to ``((block,),) * groups``.

The owned pool is the FullAttention pool: the shared pool, or pool 0 of the
decoupled layout. Every block is checked to be that pool's own object before
it is pinned or freed, so a Mamba (pool-1) block is refused even when its id
coincides with an FA block id.
"""
from dataclasses import dataclass, field
from .contract import Abort, require


@dataclass(frozen=True)
class TailPin:
    page: int          # Q/P
    start: int         # Q
    valid_end: int     # C: KV in [start, valid_end) is valid; later slots may be dirty
    groups: tuple      # ((block,),) per FullAttention group


@dataclass
class Lease:
    namespace: str
    request_id: str
    old: dict                                   # committed resident Pages at admission
    old_tail: TailPin | None
    geometry: object
    groups: int                                 # FullAttention group count
    selected: tuple = ()                        # A_t ascending
    target: dict = field(default_factory=dict)  # A_t Page -> groups (retain / tail candidate / restore)
    run: dict = field(default_factory=dict)     # run Page -> groups (live tail / adopted phase-1)
    restore_blocks: list = field(default_factory=list)  # the only engine zero-queue blocks
    acquired: list = field(default_factory=list)        # Q refs taken by begin
    adopted: list = field(default_factory=list)         # phase-1 blocks whose F ref became Q
    rows: tuple = ()                            # every FA row block, snapshot before native free
    installed_managers: list = field(default_factory=list)
    worker_started: bool = False
    phase: str = "allocating"


class PrivateBlockOwner:
    """One scheduler-owned pool; Pages map to tuples of native blocks by group.

    The namespace is generated by the server adapter, never a client cache_salt.
    Resident references belong to the session. A request borrows its own reference
    for retained blocks; new blocks initially belong to the request and acquire a
    session pin at commit, before native request free releases the borrow.
    """
    # The window layout's WindowPins (gemma-s1): close_drained frees the session's window too.
    window = None

    def __init__(self, pool):
        self.pool = pool
        self.sessions = {}
        self.tails = {}
        self.leases = {}
        self.block_namespaces = {}
        self.finished = set()

    @staticmethod
    def _blocks(pages):
        return tuple(b for groups in pages.values() for group in groups for b in group)

    def _in_pool(self, b):
        return (type(b.block_id) is int and 0 <= b.block_id < len(self.pool.blocks)
                and self.pool.blocks[b.block_id] is b)

    def pinned(self, namespace):
        """Every block holding a session pin: resident Pages plus the live tail."""
        tail = self.tails.get(namespace)
        return (self._blocks(self.sessions.get(namespace, {})) +
                (self._blocks({tail.page: tail.groups}) if tail else ()))

    def _validate(self, blocks, namespace, *, may_be_new=False):
        ids = [b.block_id for b in blocks]
        require(len(ids) == len(set(ids)), "duplicate block aliases in private table")
        for b in blocks:
            require(self._in_pool(b) and not b.is_null and
                    b.ref_cnt > 0 and b.block_hash is None,
                    "not an exclusively private allocated native block")
            owner = self.block_namespaces.get(b.block_id)
            require(owner == namespace or (may_be_new and owner is None),
                    "foreign sparse namespace block")

    @staticmethod
    def _page_groups(groups, count):
        return (type(groups) is tuple and len(groups) == count and
                all(type(g) is tuple and len(g) == 1 for g in groups))

    def discard_handover(self, handover):
        """Free adopted phase-1 blocks that never reached a lease (F: 1 -> 0)."""
        blocks = self._blocks(handover)
        require(len({b.block_id for b in blocks}) == len(blocks) and
                all(self._in_pool(b) and b.ref_cnt == 1 and
                    self.block_namespaces.get(b.block_id) is None
                    for b in blocks), "handover blocks changed owner before adoption")
        self.pool.free_blocks(reversed(blocks))

    def begin(self, namespace, request_id, geometry, selected, groups, handover):
        """Admission (spec 3.4/3.7): borrow A_t & R' and a live tail, allocate
        restore targets, adopt the phase-1 run blocks.

        Ownership of ``handover`` moves to this call: every failure frees it.
        """
        geo = geometry
        if (request_id in self.leases or request_id in self.finished or
                any(x.namespace == namespace for x in self.leases.values())):
            self.discard_handover(handover)
            raise Abort("duplicate native request ownership or session already has native work")
        lease = Lease(namespace, request_id, dict(self.sessions.get(namespace, {})),
                      self.tails.get(namespace), geo, groups, tuple(selected),
                      adopted=list(self._blocks(handover)))
        self.leases[request_id] = lease
        try:
            P, old, tail = geo.page_tokens, lease.old, lease.old_tail
            require(type(groups) is int and groups > 0 and
                    all(self._page_groups(v, groups) for v in old.values()) and
                    (tail is None or self._page_groups(tail.groups, groups)),
                    "native Page layout changed")
            self._validate(self.pinned(namespace), namespace)
            require(all(p < geo.Q // P for p in old),
                    "resident Page at or after the sealed end")
            require((tail is not None) == geo.tail and
                    (tail is None or (tail.page, tail.start, tail.valid_end) ==
                     (geo.Q // P, geo.Q, geo.C)), "session tail pin differs from turn geometry")
            require(type(selected) is tuple and selected == tuple(sorted(set(selected))) and
                    all(type(p) is int and 0 <= p < geo.n for p in selected),
                    "invalid selected Page table")
            require(type(handover) is dict and set(handover) == set(geo.fresh_pages) and
                    all(self._page_groups(v, groups) for v in handover.values()),
                    "handover must be exactly the phase-1 fresh run Pages")
            ids = [b.block_id for b in lease.adopted]
            require(len(ids) == len(set(ids)) and
                    all(self._in_pool(b) and b.ref_cnt == 1 and b.block_hash is None and
                        not b.is_null and self.block_namespaces.get(b.block_id) is None
                        for b in lease.adopted),
                    "handover block is not an exclusive phase-1 allocation")
            candidate = geo.Q // P if geo.tail_candidate else None
            restore = [p for p in selected if p not in old and p != candidate]
            require(len(restore) * groups <= self.pool.get_num_free_blocks(),
                    "insufficient native blocks")
            for page in selected:
                if page in old or page == candidate:
                    pinned = old[page] if page in old else tail.groups
                    blocks = self._blocks({page: pinned})
                    self.pool.touch(blocks)  # request borrow: S -> S+Q
                    lease.acquired.extend(blocks)
                    lease.target[page] = pinned
                else:
                    fresh = []
                    for _ in range(groups):
                        block = self.pool.get_new_blocks(1)[0]
                        lease.acquired.append(block)
                        fresh.append((block,))
                    self._validate(tuple(b for (b,) in fresh), namespace, may_be_new=True)
                    for (b,) in fresh:
                        self.block_namespaces[b.block_id] = namespace
                    lease.restore_blocks.extend(b for (b,) in fresh)
                    lease.target[page] = tuple(fresh)
            for page in geo.run_pages:
                if geo.tail_live and page == geo.Q // P:
                    blocks = self._blocks({page: tail.groups})
                    self.pool.touch(blocks)  # the live tail continues: S -> S+Q
                    lease.acquired.extend(blocks)
                    lease.run[page] = tail.groups
                else:
                    lease.run[page] = handover[page]
                    for (b,) in handover[page]:
                        self.block_namespaces[b.block_id] = namespace
            self._validate(self._blocks(lease.target) + self._blocks(lease.run), namespace)
            lease.phase = "allocated"
            return lease
        except BaseException:
            # These references have not reached a worker yet; synchronous undo.
            self.abort_unsubmitted(request_id)
            raise

    def install_tables(self, request_id, managers):
        """Install [A_t][run] into the FA manager tables before the request runs.

        Only FullAttentionManager uses this table layout. Mamba rows stay native.
        The zero queue gets restore targets only: never retained, tail or
        adopted phase-1 blocks (spec 3.6).
        """
        lease = self.leases[request_id]
        require(lease.phase == "allocated", "tables already installed")
        require(len(managers) == lease.groups, "group mismatch")
        for m in managers:
            require(type(m).__name__ == "FullAttentionManager" and
                    m.block_pool is self.pool and not m.req_to_blocks.get(request_id),
                    "unsupported/occupied native group table")
        head = ([lease.target[p] for p in lease.selected] +
                [lease.run[p] for p in lease.geometry.run_pages])
        tables = tuple(tuple(groups[i][0] for groups in head) for i in range(len(managers)))
        restore = {b.block_id for b in lease.restore_blocks}
        lease.phase = "installing"
        for m, table in zip(managers, tables):
            # Record before the first table mutation, so a partial installation
            # can remove its bookkeeping without requiring an absent worker.
            lease.installed_managers.append(m)
            m.req_to_blocks[request_id] = list(table)
            m.num_cached_block[request_id] = 0
            m.new_block_ids.extend(b.block_id for b in table if b.block_id in restore)
        lease.phase = "installed"
        return tables

    def mark_submitted(self, request_id):
        lease = self.leases[request_id]
        require(lease.phase == "installed" and not lease.worker_started,
                "invalid native submission ownership")
        lease.worker_started = True

    def row_groups(self, request_id, page):
        """FA groups of a logical Page in the request's current row (spec 3.8)."""
        lease = self.leases[request_id]
        if page in lease.target:
            return lease.target[page]
        P = lease.geometry.page_tokens
        base, a = lease.geometry.L // P, len(lease.selected)
        rows = [m.req_to_blocks.get(request_id, ()) for m in lease.installed_managers]
        index = a + page - base
        require(page >= base and rows and all(index < len(row) for row in rows),
                "logical Page outside the native row")
        return tuple((row[index],) for row in rows)

    def _remove_pending_zero_ids(self, lease):
        # take_new_block_ids() is a pending zero queue in vLLM, not a durable
        # allocation audit. A freed/reused block ID must never survive here.
        ids = {b.block_id for b in (*lease.acquired, *lease.adopted, *lease.rows)}
        for manager in lease.installed_managers:
            ids.update(b.block_id for b in manager.req_to_blocks.get(lease.request_id, ())
                       if not b.is_null)
        for manager in lease.installed_managers:
            manager.new_block_ids[:] = [i for i in manager.new_block_ids if i not in ids]

    def commit(self, request_id, *, keep_pages, tail):
        """Called only after authenticated worker completion/drain (spec 3.8).

        keep = blocks of keep_pages plus the new tail. Touch keep - pinned before
        native free; free pinned - keep, which must not be in the row.
        """
        lease = self.leases[request_id]
        require(lease.phase == "installed", "commit phase mismatch")
        geo, ns = lease.geometry, lease.namespace
        P = geo.page_tokens
        rows = tuple(tuple(m.req_to_blocks.get(request_id, ())) for m in lease.installed_managers)
        head = ([lease.target[p] for p in lease.selected] +
                [lease.run[p] for p in geo.run_pages])
        require(len(rows) == lease.groups and
                all(row[:len(head)] == tuple(g[i][0] for g in head) for i, row in enumerate(rows)),
                "committed FA row head moved after admission")
        require(type(keep_pages) is tuple and keep_pages == tuple(sorted(set(keep_pages))),
                "kept Pages must be ascending and unique")
        keep = {p: self.row_groups(request_id, p) for p in keep_pages}
        pin = None
        if tail is not None:
            page, start, valid_end = tail
            require(start == page * P < valid_end < start + P and page not in keep and
                    page >= geo.L // P, "invalid tail pin")
            pin = TailPin(page, start, valid_end, self.row_groups(request_id, page))
        kept = self._blocks(keep) + (self._blocks({pin.page: pin.groups}) if pin else ())
        before = self.pinned(ns)
        kept_ids, before_ids = {b.block_id for b in kept}, {b.block_id for b in before}
        row_ids = {b.block_id for row in rows for b in row}
        add = [b for b in kept if b.block_id not in before_ids]
        drop = [b for b in before if b.block_id not in kept_ids]
        require(len(kept_ids) == len(kept) and kept_ids <= row_ids and
                not {b.block_id for b in drop} & row_ids,
                "kept blocks must be in the row and released blocks must not")
        require(all(b.ref_cnt == 1 for b in add) and all(b.ref_cnt == 1 for b in drop) and
                all(b.ref_cnt == 2 for b in kept if b.block_id in before_ids),
                "unexpected block owner before commit")
        self._validate(add, ns, may_be_new=True)
        self._validate(before, ns)
        self.pool.touch(add)
        for b in add:
            self.block_namespaces[b.block_id] = ns
        self.pool.free_blocks(reversed(drop))
        for b in drop:
            require(b.ref_cnt == 0, "released Page still has an unexpected native owner")
            self.block_namespaces.pop(b.block_id)
        self.sessions[ns] = keep
        if pin is None:
            self.tails.pop(ns, None)
        else:
            self.tails[ns] = pin
        lease.phase = "committed"

    def before_native_free(self, request_id):
        lease = self.leases[request_id]
        require(lease.phase in {"committed", "cancelled_drained"},
                "native free before completion/cancellation drain")
        lease.rows = tuple(b for m in lease.installed_managers
                           for b in m.req_to_blocks.get(request_id, ()) if not b.is_null)
        self._remove_pending_zero_ids(lease)
        lease.phase = "freeing"

    def after_native_free(self, request_id):
        lease = self.leases[request_id]
        require(lease.phase == "freeing", "double-free or absent native free fence")
        pinned = {b.block_id for b in self.pinned(lease.namespace)}
        seen = {b.block_id: b for b in (*lease.rows, *lease.acquired, *lease.adopted)}
        for b in seen.values():
            require(b.ref_cnt == (1 if b.block_id in pinned else 0),
                    "native free did not release exactly the request borrow")
            if b.block_id not in pinned:
                self.block_namespaces.pop(b.block_id, None)
        self.finished.add(request_id)
        del self.leases[request_id]

    def cancel_drained(self, request_id):
        lease = self.leases[request_id]
        require(lease.phase == "installed", "cannot rollback committed/freeing request")
        lease.phase = "cancelled_drained"

    def abort_unsubmitted(self, request_id):
        lease = self.leases.get(request_id)
        if lease is None:
            # Capacity/preflight rejection may occur before a lease exists;
            # previously cleaned attempts are also safe to clean again.
            self.finished.add(request_id)
            return
        require(not lease.worker_started and lease.phase in
                {"allocating", "allocated", "installing", "installed"},
                "native drain required")
        self._remove_pending_zero_ids(lease)
        for manager in lease.installed_managers:
            manager.req_to_blocks.pop(request_id, None)
            manager.num_cached_block.pop(request_id, None)
        released = (*lease.acquired, *lease.adopted)
        self.pool.free_blocks(reversed(released))
        for b in released:
            if b.ref_cnt == 0:
                self.block_namespaces.pop(b.block_id, None)
        del self.leases[request_id]
        self.finished.add(request_id)

    def evict(self, namespace):
        """--release-idle-pages: release an idle session's resident Pages (S -> 0); the
        live tail stays pinned. Returns the released Page -> groups map."""
        require(not any(x.namespace == namespace for x in self.leases.values()),
                "cannot evict while a native request exists")
        resident = self.sessions.get(namespace, {})
        blocks = self._blocks(resident)
        self._validate(blocks, namespace)
        require(all(b.ref_cnt == 1 for b in blocks), "evicted Page blocks are borrowed")
        self.pool.free_blocks(reversed(blocks))
        for b in blocks:
            self.block_namespaces.pop(b.block_id)
        self.sessions[namespace] = {}
        return resident

    def readmit(self, namespace, pages, groups):
        """--release-idle-pages: fresh pinned blocks (S = 1) for an evicted session's
        Pages before its next turn; the worker restores their DRAM copies into them.
        Returns the Page -> groups map, now the session's resident Pages."""
        require(not any(x.namespace == namespace for x in self.leases.values()) and
                not self.sessions.get(namespace) and type(groups) is int and groups > 0 and
                type(pages) is tuple and pages == tuple(sorted(set(pages))) and pages,
                "readmission needs an idle session without resident Pages")
        require(len(pages) * groups <= self.pool.get_num_free_blocks(), "insufficient native blocks")
        tail = self.tails.get(namespace)
        require(tail is None or all(p < tail.page for p in pages), "readmitted Page at or after the tail")
        resident = {}
        for page in pages:
            fresh = []
            for _ in range(groups):
                block = self.pool.get_new_blocks(1)[0]
                fresh.append((block,))
            blocks = tuple(b for (b,) in fresh)
            self._validate(blocks, namespace, may_be_new=True)
            for b in blocks:
                self.block_namespaces[b.block_id] = namespace
            resident[page] = tuple(fresh)
        self.sessions[namespace] = resident
        return resident

    def close_drained(self, namespace):
        """Session close (shutdown or rebuild): free resident Pages and the tail."""
        require(not any(x.namespace == namespace for x in self.leases.values()),
                "cannot close while native request exists")
        blocks = self.pinned(namespace)
        self._validate(blocks, namespace)
        require(all(b.ref_cnt == 1 for b in blocks), "unexpected borrowed blocks")
        self.pool.free_blocks(reversed(blocks))
        for b in blocks:
            self.block_namespaces.pop(b.block_id)
        self.sessions.pop(namespace, None)
        self.tails.pop(namespace, None)
        if self.window is not None:
            self.window.close(namespace)
