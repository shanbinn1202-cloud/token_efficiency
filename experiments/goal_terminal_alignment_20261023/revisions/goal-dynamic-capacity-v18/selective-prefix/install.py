#!/usr/bin/env python3
"""Check or create an isolated, default-OFF release; never mutate site-packages."""
import argparse
import base64
import csv
from hashlib import sha256
import io
import json
import os
from pathlib import Path,PurePosixPath
import platform
import re
import shutil
import stat
import sys

ROOT=Path(__file__).resolve().parent
def digest(raw):return sha256(raw).hexdigest()
def encoded(value):return (json.dumps(value,sort_keys=True,indent=2)+'\n').encode()
def need(ok,message):
    if not ok:raise ValueError(message)
def save(path,raw):
    with path.open('xb') as stream:stream.write(raw);stream.flush();os.fsync(stream.fileno())
def safe(root,name):
    part=PurePosixPath(name)
    need(not part.is_absolute() and part.parts and '..' not in part.parts and '\\' not in name,'unsafe release path')
    target=root.joinpath(*part.parts);cursor=target
    while cursor!=root:
        need(not cursor.is_symlink(),'symlinked release path: '+name);cursor=cursor.parent
    need(target.resolve().is_relative_to(root.resolve()),'release path escaped')
    return target
def inventory(root):
    need(root.is_dir() and not root.is_symlink(),'regular directory required')
    result={}
    for path in root.rglob('*'):
        need(not path.is_symlink(),'symlink in owned tree: '+str(path))
        if '__pycache__' in path.parts or path.suffix in ('.pyc','.pyo'):continue
        if path.is_dir():continue
        need(path.is_file(),'nonregular file in owned tree')
        result[path.relative_to(root).as_posix()]=digest(path.read_bytes())
    return result

def verify_package(root=ROOT):
    definition=json.loads((root/'INSTALL_RELEASE.json').read_bytes())
    need(definition['format_version']==3 and definition['feature_default']=='off','unsupported package')
    sources=definition['source_files'];actual=inventory(root/'source-overlay')
    need(actual==sources,'source-overlay coverage or hash mismatch')
    lines=''.join(f'{pin}  source-overlay/{name}\n' for name,pin in sorted(sources.items())).encode()
    need((root/'SOURCE_SHA256SUMS.txt').read_bytes()==lines,'source checksum manifest mismatch')
    expected=definition['expected_live']
    need(set(expected)=={n for n in sources if n.startswith('vllm/')},'baseline coverage mismatch')
    need(definition['payload']=={n:p for n,p in sources.items() if expected.get(n)!=p},'payload coverage mismatch')
    need(set(definition['source_closure']['files'])<=set(sources),'native source closure incomplete')
    need(all(sources[name]==pin for name,pin in definition['source_closure']['files'].items()),
         'source closure hash differs from delivered source')
    need(definition['source_closure']['manifest_sha256']==digest(json.dumps(
        definition['source_closure']['files'],sort_keys=True,separators=(',',':')).encode()),
        'source closure inventory digest mismatch')
    for name,pin in expected.items():need(pin is None or re.fullmatch('[0-9a-f]{64}',pin),'bad baseline digest')
    # Other model profiles (gemma-s1): a release is installed for one model; the default
    # is the top-level Qwen pins. Each profile pins its own metadata files and revision.
    for name,profile in definition.get('model_profiles',{}).items():
        need(re.fullmatch('[a-z0-9.-]+',name) and type(profile) is dict and set(profile)=={'model_pins','model_revision'}
             and re.fullmatch('[0-9a-f]{40}',profile['model_revision']) and profile['model_pins']
             and all(re.fullmatch('[0-9a-f]{64}',p) and '/' not in n for n,p in profile['model_pins'].items()),
             'bad model profile pins: '+name)
    for name in sources:
        if name.endswith('.py'):compile(safe(root/'source-overlay',name).read_bytes(),name,'exec')
    return definition

def metadata_version(site,name):
    paths=list(site.glob(name.replace('-','_')+'-*.dist-info/METADATA'))
    need(len(paths)==1,'exact one '+name+' distribution metadata required')
    fields={}
    for line in paths[0].read_text(encoding='utf-8').splitlines():
        if line.startswith(('Name: ','Version: ')):
            key,value=line.split(': ',1);fields[key]=value.strip()
    need(fields.get('Name','').lower().replace('-','_')==name.replace('-','_'),'distribution name mismatch')
    return fields.get('Version')

def verify_vllm_record(site):
    """Verify all copied package files against the installed wheel's RECORD.

    RECORD is an integrity inventory, not an independent signature of PyPI.
    Install the base wheel from a trusted source. Installer-generated bytecode
    is excluded from both this check and the copied tree. Entries outside vllm/
    (scripts, dist-info, RECORD itself) are not copied and need not have hashes.
    """
    record=safe(site,'vllm-0.24.0.dist-info/RECORD')
    need(record.is_file(),'vllm 0.24.0 wheel RECORD required; editable installs unsupported')
    raw=record.read_bytes();expected={};sizes={}
    for row in csv.reader(io.StringIO(raw.decode('utf-8'))):
        need(len(row)==3,'malformed wheel RECORD row')
        name,pin,size=row
        if not name.startswith('vllm/'):continue
        safe(site,name)
        if '__pycache__' in PurePosixPath(name).parts or name.endswith(('.pyc','.pyo')):continue
        need(name not in expected,'duplicate vllm RECORD entry: '+name)
        need(pin.startswith('sha256=') and re.fullmatch(r'\d+',size) is not None,
             'vllm RECORD file requires SHA256 and size: '+name)
        try:decoded=base64.b64decode(pin[7:]+'='*((-len(pin[7:]))%4),altchars=b'-_',validate=True)
        except ValueError:raise ValueError('invalid RECORD digest: '+name) from None
        need(len(decoded)==32,'invalid RECORD SHA256: '+name)
        expected[name]=decoded.hex();sizes[name]=int(size)
    actual={'vllm/'+name:pin for name,pin in inventory(site/'vllm').items()}
    need(expected and actual==expected,'vllm RECORD coverage/hash mismatch (extra, missing or changed package file)')
    for name,size in sizes.items():need(safe(site,name).stat().st_size==size,'vllm RECORD size mismatch: '+name)
    return actual,dict(path='vllm-0.24.0.dist-info/RECORD',sha256=digest(raw),files=len(actual))

def environment_identity(site):
    """Canonical aliases are equivalent; sys.path ordering is not an identity."""
    executable=Path(sys.executable).resolve()
    return dict(python_version=list(sys.version_info[:3]),implementation=sys.implementation.name,
        machine=platform.machine().lower(),executable=str(executable),executable_sha256=digest(executable.read_bytes()),
        prefix=str(Path(sys.prefix).resolve()),site=str(Path(site).resolve()))

def verify_environment_identity(manifest):
    expected=manifest.get('environment_identity')
    need(type(expected) is dict,'release lacks interpreter identity; reinstall with this installer')
    actual=environment_identity(manifest['site'])
    for name in actual:need(actual[name]==expected.get(name),'release environment mismatch: '+name)

def model_definition(definition,profile=None):
    """(model_pins, model_revision) of the release's model: the top-level Qwen pins, or
    those of a named model profile (``--model-profile``, gemma-s1)."""
    if profile is None:return definition['model_pins'],definition['model_revision']
    profiles=definition.get('model_profiles',{})
    need(profile in profiles,'unknown model profile: %s (known: %s)'%(profile,', '.join(sorted(profiles)) or 'none'))
    return profiles[profile]['model_pins'],profiles[profile]['model_revision']

def check_environment(site,model,definition,profile=None):
    need(sys.version_info[:2]==(3,12),'supported target interpreter is Python 3.12')
    need(site.is_dir() and (site/'vllm').is_dir(),'explicit site-packages with vLLM required')
    for name,version in definition['qualified_dependency_versions'].items():
        need(metadata_version(site,name)==version,'required distribution version: '+name+'=='+version)
    baseline,_=verify_vllm_record(site)
    for name,pin in definition['expected_live'].items():
        path=safe(site,name)
        if pin is None:need(not path.exists(),'upstream-absent target exists: '+name)
        else:need(path.is_file() and digest(path.read_bytes())==pin,'clean v0.24.0 baseline mismatch: '+name)
    for name,pin in model_definition(definition,profile)[0].items():
        need(safe(model,name).is_file() and digest(safe(model,name).read_bytes())==pin,'pinned model/tokenizer metadata mismatch: '+name)
    native={}
    for package in ('transformers','tokenizers','jinja2','markupsafe'):
        for name,pin in inventory(site/package).items():
            relative=package+'/'+name
            if name.endswith('.py'):baseline[relative]=pin
            elif Path(name).suffix in ('.so','.pyd','.dll'):
                native[relative]=dict(sha256=pin,size=(site/relative).stat().st_size)
    need(any(n.startswith('tokenizers/') for n in native),'native tokenizer library missing')
    return baseline,native

def installed_check(release):
    release=Path(release).absolute();need(not release.is_symlink(),'release symlink prohibited')
    index=json.loads((release/'release-index.json').read_bytes())
    need(digest((release/'release-index.json').read_bytes())==
         (release/'release-index.sha256').read_text().split()[0],'release index changed')
    actual=inventory(release);actual.pop('release-index.json');actual.pop('release-index.sha256')
    need(actual==index['files'],'installed release drift or extra files')
    manifest=json.loads((release/'runtime-manifest.json').read_bytes())
    need(digest((release/'runtime-manifest.json').read_bytes())==index['manifest_sha256'],'manifest/index mismatch')
    need((release/'runtime-manifest.sha256').read_text().split()[0]==index['manifest_sha256'],'manifest sidecar mismatch')
    for name,pin in manifest['source_files'].items():need(actual.get('source/'+name)==pin,'installed source mismatch')
    verify_environment_identity(manifest)
    return manifest

def remove_owned(root,identity):
    need(not root.is_symlink() and root.is_dir(),'owned release directory changed')
    now=root.stat();need((now.st_dev,now.st_ino)==identity,'owned release identity changed')
    root.chmod(stat.S_IRUSR|stat.S_IWUSR|stat.S_IXUSR)
    for path in root.rglob('*'):
        need(not path.is_symlink(),'symlink appeared in incomplete owned release')
        if path.is_dir():path.chmod(stat.S_IRUSR|stat.S_IWUSR|stat.S_IXUSR)
    def writable_retry(function,path,error):
        if not isinstance(error,PermissionError):raise error
        Path(path).chmod(stat.S_IRUSR|stat.S_IWUSR|stat.S_IXUSR)
        function(path)
    shutil.rmtree(root,onexc=writable_retry)

def copy_owned(source,destination):
    # copy2 carries read-only wheel modes to the new tree and can prevent the
    # overlay or rollback. Preserve bytes, set modes on our copy only.
    shutil.copyfile(source,destination)
    Path(destination).chmod(stat.S_IMODE(Path(source).stat().st_mode)|stat.S_IRUSR|stat.S_IWUSR)
    return destination

def install(site,model,release,*,apply=False,package_root=ROOT,fail_after=None,model_profile=None):
    """model_profile: None (the Qwen model, the manifest unchanged) or a named profile of
    INSTALL_RELEASE.json model_profiles (gemma-s1: gemma4-31b-it), recorded in the manifest."""
    site=Path(site).resolve(strict=True);model=Path(model).resolve(strict=True);release=Path(release).absolute()
    need(not release.exists() and not release.is_symlink(),'new release directory required')
    need(release.parent.is_dir() and release!=Path(release.anchor),'existing explicit release parent required')
    for protected in (site,model,Path(package_root).resolve()):
        need(not release.resolve().is_relative_to(protected),'release must be outside environment/model/package')
    definition=verify_package(package_root);baseline,native=check_environment(site,model,definition,model_profile)
    model_pins,model_revision=model_definition(definition,model_profile)
    result=dict(status='CHECK_ONLY_PASS',mutated=False,site_packages_written=False,
        feature_default='off',source_files=len(definition['source_files']),release=str(release))
    if model_profile is not None:result.update(model_profile=model_profile)
    if not apply:return result
    release.mkdir(mode=0o700);info=release.stat();identity=(info.st_dev,info.st_ino)
    try:
        shutil.copytree(site/'vllm',release/'source/vllm',copy_function=copy_owned,
            ignore=shutil.ignore_patterns('__pycache__','*.pyc','*.pyo'))
        # copytree also preserves directory modes; make only this owned copy writable.
        for directory in [release/'source/vllm',*(p for p in (release/'source/vllm').rglob('*') if p.is_dir())]:
            directory.chmod(stat.S_IRUSR|stat.S_IWUSR|stat.S_IXUSR)
        need(inventory(release/'source/vllm')=={n.removeprefix('vllm/'):p for n,p in baseline.items() if n.startswith('vllm/')},'baseline changed while copying')
        for i,(name,pin) in enumerate(definition['source_files'].items(),1):
            target=safe(release/'source',name);target.parent.mkdir(parents=True,exist_ok=True)
            raw=safe(Path(package_root)/'source-overlay',name).read_bytes();need(digest(raw)==pin,'payload changed during install')
            target.write_bytes(raw)
            if i==fail_after:raise RuntimeError('injected installer failure')
        after,native_after=check_environment(site,model,definition,model_profile)
        need(after==baseline and native_after==native,'environment changed during install')
        manifest=dict(schema='selective-prefix-portable-runtime-v1',site=str(site),model_root=str(model),
            environment_identity=environment_identity(site),upstream_record=verify_vllm_record(site)[1],
            source_files=definition['source_files'],baseline_files=baseline,native_pins=native,
            model_pins=model_pins,source_closure=definition['source_closure'],
            qualification_parent_manifest='cc5b8c5b10818b12750cf9f1702a75b3753bf61b0fb3d3934af1057d8250bebb',
            release_id=definition['release_id'],default_enabled=False,provenance=definition['provenance'],
            model_revision=model_revision)
        if model_profile is not None:
            manifest.update(model_profile=model_profile)
        raw=encoded(manifest);save(release/'runtime-manifest.json',raw)
        save(release/'runtime-manifest.sha256',(digest(raw)+'  runtime-manifest.json\n').encode())
        index=dict(manifest_sha256=digest(raw),files=inventory(release));raw=encoded(index)
        save(release/'release-index.json',raw);save(release/'release-index.sha256',(digest(raw)+'  release-index.json\n').encode())
        installed_check(release)
    except BaseException as original:
        try:remove_owned(release,identity)
        except BaseException as cleanup:raise BaseExceptionGroup('install and rollback failed',[original,cleanup]) from None
        raise
    return dict(result,status='INSTALL_PASS',mutated=True,site_packages_written=False)

def uninstall(release,*,apply=False,processes_stopped=False):
    release=Path(release).absolute();installed_check(release);need(release!=Path(release.anchor),'root is not a release')
    info=release.stat();identity=(info.st_dev,info.st_ino)
    if apply:
        need(processes_stopped,'stop every process using this release and confirm --processes-stopped')
        import secrets
        backup=release.with_name(release.name+'.uninstalled-'+secrets.token_hex(8));need(not backup.exists(),'quarantine collision')
        need((release.stat().st_dev,release.stat().st_ino)==identity,'release changed before uninstall')
        release.rename(backup)
        return dict(status='UNINSTALL_PASS',backup=str(backup),site_packages_written=False)
    return dict(status='UNINSTALL_CHECK_PASS',site_packages_written=False)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--site-packages',type=Path,required=True)
    parser.add_argument('--model-dir',type=Path,required=True)
    parser.add_argument('--release-dir',type=Path,required=True)
    parser.add_argument('--model-profile',
        help='install for another model of INSTALL_RELEASE.json model_profiles (gemma4-31b-it: stage 1, '
             'not GPU-validated); default: Qwen3.6-27B')
    parser.add_argument('--apply',action='store_true');args=parser.parse_args()
    profile={} if args.model_profile is None else dict(model_profile=args.model_profile)
    print(json.dumps(install(args.site_packages,args.model_dir,args.release_dir,apply=args.apply,**profile),
                     sort_keys=True))
if __name__=='__main__':main()
